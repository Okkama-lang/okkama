//! Compile-first documentation tests (#514), using the compiler doc model.
//! Execution is an opt-in child with no host capabilities, no inherited
//! credentials, bounded memory/output/time, and a disposable working directory.

use std::io::Read;
use std::path::PathBuf;
use std::process::{Command, Stdio};
use std::sync::{Arc, atomic::{AtomicBool, AtomicUsize, Ordering}};
use std::time::{Duration, Instant};
use okkama_compiler::doc::{ModuleDoc, examples::{Example, ExampleKind}};
use super::*;

const TIMEOUT: Duration = Duration::from_secs(3);
const MEMORY: u64 = 64 << 20;
#[cfg(unix)]
const PROCESS_MEMORY: u64 = 256 << 20;
const OUTPUT: usize = 64 << 10;

fn failure(source: &SourceFile, span: Span, message: &str) -> Outcome {
    let location = source.location(span.start);
    Outcome::failure(format!("{}:{}:{}: doctest error: {message}\n", source.name(), location.line, location.column), EXIT_DIAGNOSTICS)
}

/// The gate applies only to roots in completed std waves, never dependencies
/// or user files that happen to declare the same module name.
pub(super) fn gate(sources: &[SourceFile]) -> Result<(), Outcome> {
    let mut loader = loader(false);
    for source in sources {
        if !okkama_compiler::doc::coverage::enforced_file(source.name(), &mut loader) { continue; }
        // Parsing failures belong to the normal frontend, which retains all
        // diagnostics and their exact locations; this gate only adds lint.
        let Ok(doc) = ModuleDoc::parse(source.name().into(), source.text().into()) else { continue; };
        if let Some(missing) = doc.coverage().missing.first() {
            let location = source.location(missing.span.start);
            return Err(Outcome::failure(format!("{}:{}:{}: error[missing-docs]: public declaration `{}` has no documentation\n", source.name(), location.line, location.column, missing.name), EXIT_DIAGNOSTICS));
        }
    }
    Ok(())
}

pub(super) fn check(sources: &[SourceFile], filters: &[String]) -> Outcome {
    if let Err(outcome) = parse_raw(sources) { return outcome; }
    if let Err(outcome) = gate(sources) { return outcome; }
    let mut report = String::new();
    for source in sources {
        let doc = match ModuleDoc::parse(source.name().into(), source.text().into()) {
            Ok(doc) => doc,
            Err(message) => return Outcome::failure(message, EXIT_DIAGNOSTICS),
        };
        let examples = match doc.examples() {
            Ok(examples) => examples,
            Err(error) => return failure(source, error.span, &error.message),
        };
        for example in examples {
            if example.kind == ExampleKind::Illustrative { continue; }
            let name = format!("doctest {}:{}", source.name(), source.location(example.span.start).line);
            if !filters.is_empty() && !filters.iter().any(|filter| name.contains(filter)) { continue; }
            let bytes = match compile(sources, source, &example) {
                Ok(bytes) => bytes,
                Err(outcome) => return outcome,
            };
            let mode = if example.kind == ExampleKind::Run {
                match execute(&bytes) {
                    Ok(Execution::Checked(stdout, stderr)) => {
                        if !stderr.is_empty() { return failure(source, example.span, &format!("unexpected stderr: {:?}", String::from_utf8_lossy(&stderr))); }
                        let expected = example.expected.as_ref().unwrap().as_bytes();
                        if stdout != expected {
                            return failure(source, example.span, &format!("expected stdout {:?}, got {:?}", example.expected.as_ref().unwrap(), String::from_utf8_lossy(&stdout)));
                        }
                        "run".to_string()
                    }
                    Ok(Execution::CompileOnly(reason)) => format!("compile-only: isolation unavailable ({reason})"),
                    Err(message) => return failure(source, example.span, &message),
                }
            } else { "compile".to_string() };
            report.push_str(&format!("ok - {name} ({mode})\n"));
        }
    }
    Outcome::success(report)
}

/// Generated bytes map either to a byte of the snippet or to its own source
/// imports. Wrapper tokens point to the fence, never an invented file line.
struct Prepared { source: SourceFile, offsets: Vec<u32>, standalone: bool }

fn prepare(source: &SourceFile, program: &ast::Program, example: &Example) -> Prepared {
    use okkama_compiler::syntax::token::TokenKind;
    let tokens = lexer::lex(&example.code).tokens;
    let standalone = tokens.first().is_some_and(|token| token.kind == TokenKind::Module);
    let mut text = String::new();
    let mut offsets = Vec::new();
    let mut push = |value: &str, mapping: Option<Vec<u32>>| {
        text.push_str(value);
        offsets.extend(mapping.unwrap_or_else(|| vec![example.span.start; value.len()]));
    };
    if !standalone {
        push(source.slice(program.module.span), Some((program.module.span.start..program.module.span.end).collect()));
        push("\n", None);
        for import in &program.imports {
            push(source.slice(import.span), Some((import.span.start..import.span.end).collect()));
            push("\n", None);
        }
    }
    let header_len = text.len();
    text.push_str(&example.code);
    offsets.extend((0..example.code.len()).map(|i| example.source_span(Span::empty(i as u32)).start));
    let options = ParseOptions { mode: ParseMode::Full, ..ParseOptions::default() };
    let trial = SourceFile::new("<doctest>", text.clone()).unwrap();
    if let Ok(parsed) = syntax::parse(&trial, &options) {
        if !parsed.items.iter().any(|item| matches!(item, ast::Item::Action(action) if action.name.text == "main")) {
            let tail = "\nmain() is int { 0; }\n";
            text.push_str(tail); offsets.extend(vec![example.span.end; tail.len()]);
        }
    } else if !standalone {
        // Only leading imports are lifted out of a statement example. No
        // textual search for `main()` (including in strings or comments).
        let mut imports_end = 0;
        let mut index = 0;
        while tokens.get(index).is_some_and(|token| token.kind == TokenKind::Import) {
            while index < tokens.len() && tokens[index].kind != TokenKind::Semicolon { index += 1; }
            if let Some(token) = tokens.get(index) { imports_end = token.span.end as usize; index += 1; }
            else { break; }
        }
        let declaration = tokens.get(index).is_some_and(|token| {
            matches!(token.kind, TokenKind::Object | TokenKind::Role | TokenKind::Enum | TokenKind::Native | TokenKind::Const | TokenKind::Async | TokenKind::Test | TokenKind::Fake)
                || ["main", "cap", "hidden"].contains(&&example.code[token.span.range()])
        });
        if declaration { return Prepared { source: SourceFile::new(format!("{}.doctest.ok", source.name()), text).unwrap(), offsets, standalone }; }
        let at = header_len + imports_end;
        let wrapper = "\nmain() is int {\n";
        text.insert_str(at, wrapper);
        offsets.splice(at..at, vec![example.span.start; wrapper.len()]);
        let tail = "\n0;\n}\n";
        text.push_str(tail); offsets.extend(vec![example.span.end; tail.len()]);
    }
    Prepared { source: SourceFile::new(format!("{}.doctest.ok", source.name()), text).unwrap(), offsets, standalone }
}

struct Compiled {
    bytes: Vec<u8>, module: ir::Module, prepared: Prepared, original: SourceFile, fence: Span,
}

impl Compiled {
    fn locations(&self, trace: &[[u32; 2]]) -> String {
        let mut locations = Vec::new();
        for &[function, pc] in trace {
            let id = ir::FuncId(function as usize);
            let Some(file) = self.module.source_of(id) else { continue; };
            let Some(span) = self.module.functions.get(id.0).and_then(|func| func.span_at(pc)) else { continue; };
            let (file, offset) = if file.name() == self.prepared.source.name() {
                (&self.original, self.prepared.offsets.get(span.start as usize).copied().unwrap_or(self.fence.start))
            } else { (file, span.start) };
            let at = file.location(offset);
            let line = format!("  at {}:{}:{}\n", file.name(), at.line, at.column);
            if !locations.contains(&line) { locations.push(line); }
            if locations.len() == 16 { break; }
        }
        locations.concat()
    }
}

fn compile(sources: &[SourceFile], source: &SourceFile, example: &Example) -> Result<Compiled, Outcome> {
    let mut programs = parse_all(sources, false)?;
    let original = sources.iter().position(|file| file.name() == source.name()).unwrap();
    let prepared = prepare(source, &programs[original], example);
    let map = |span: Span| {
        let start = prepared.offsets.get(span.start as usize).copied().unwrap_or(example.span.end);
        let end = prepared.offsets.get(span.end.saturating_sub(1) as usize).map_or(start, |offset| offset + 1);
        Span::new(start, end.max(start))
    };
    let options = ParseOptions { mode: ParseMode::Full, ..ParseOptions::default() };
    let program = syntax::parse(&prepared.source, &options).map_err(|errors| {
        let error = &errors[0]; failure(source, map(error.span), &format!("compilation failed: {}", error.message))
    })?;
    let tests = okkama_compiler::ide::program_has_tests(&program);
    let program = if tests { prune::desugar_test_items(program) } else { prune::strip_test_items(program) };
    for program in &mut programs {
        program.items.retain(|item| !matches!(item, ast::Item::Action(action) if action.name.text == "main"));
    }
    let mut roots = if prepared.standalone { Vec::new() } else { root_files(sources, &programs) };
    roots.push(RootFile { source: &prepared.source, program: &program });
    let mut resolver = loader(tests);
    let lowered = if tests { lowering::lower_linked_tests(&roots, &mut resolver) }
        else { lowering::lower_linked_files(&roots, &mut resolver) };
    let (module, _) = lowered.map_err(|error| match error {
        LinkError::Lowering { source: file, error } => {
            let file = file.as_ref().unwrap_or(&prepared.source);
            if file.name() == prepared.source.name() { failure(source, map(error.span()), &format!("compilation failed: {}", error.message())) }
            else { failure(file, error.span(), &format!("compilation failed for doctest at {}:{}: {}", source.name(), source.location(example.span.start).line, error.message())) }
        }
        LinkError::Load(message) => failure(source, example.span, &message),
    })?;
    let program = codegen::sparrow::generate(&module).map_err(|error| failure(source, map(error.span), &error.to_string()))?;
    let bytes = okkama_sparrow::encode(&program).map_err(|error| failure(source, example.span, &error.to_string()))?;
    Ok(Compiled { bytes, module, prepared, original: source.clone(), fence: example.span })
}

/// Creation is atomic; never reuse a caller-provided directory or symlink.
struct Directory(PathBuf);
impl Directory {
    fn new() -> Result<Self, String> {
        static SERIAL: AtomicUsize = AtomicUsize::new(0);
        for _ in 0..100 {
            let path = std::env::temp_dir().join(format!("okkama-doctest-{}-{}", std::process::id(), SERIAL.fetch_add(1, Ordering::Relaxed)));
            let mut builder = std::fs::DirBuilder::new();
            #[cfg(unix)] {
                use std::os::unix::fs::DirBuilderExt;
                builder.mode(0o700);
            }
            match builder.create(&path) {
                Ok(()) => {
                    let mut directory = Self(path);
                    directory.0 = std::fs::canonicalize(&directory.0).map_err(|e| e.to_string())?;
                    return Ok(directory);
                },
                Err(error) if error.kind() == io::ErrorKind::AlreadyExists => continue,
                Err(error) => return Err(error.to_string()),
            }
        }
        Err("cannot create isolated doctest directory".into())
    }
}
impl Drop for Directory { fn drop(&mut self) { let _ = std::fs::remove_dir_all(&self.0); } }

/// Every early return kills and reaps only this child, including failures to
/// create capture threads or poll the process.
struct RunningChild(std::process::Child);
impl Drop for RunningChild {
    fn drop(&mut self) { let _ = self.0.kill(); let _ = self.0.wait(); }
}

fn capture(
    mut stream: impl Read + Send + 'static,
    used: Arc<AtomicUsize>,
    exceeded: Arc<AtomicBool>,
) -> Result<std::thread::JoinHandle<io::Result<Vec<u8>>>, String> {
    std::thread::Builder::new().name("doctest-output".into()).spawn(move || {
        let mut output = Vec::new();
        let mut buf = [0; 4096];
        loop {
            let n = match stream.read(&mut buf) {
                Ok(n) => n,
                Err(error) if error.kind() == io::ErrorKind::Interrupted => continue,
                Err(error) => return Err(error),
            };
            if n == 0 { break; }
            let before = used.fetch_add(n, Ordering::Relaxed);
            let keep = n.min(OUTPUT.saturating_sub(before));
            output.extend_from_slice(&buf[..keep]);
            if before.saturating_add(n) > OUTPUT { exceeded.store(true, Ordering::Relaxed); }
        }
        Ok(output)
    }).map_err(|e| format!("cannot capture doctest output: {e}"))
}

enum Execution { Checked(Vec<u8>, Vec<u8>), CompileOnly(String) }

fn execute(compiled: &Compiled) -> Result<Execution, String> {
    if compiled.module.tests.is_some() {
        return Ok(Execution::CompileOnly("inline test profiles have no bounded execution path".into()));
    }
    let dir = match Directory::new() {
        Ok(dir) => dir,
        Err(reason) => return Ok(Execution::CompileOnly(reason)),
    };
    let bytecode = dir.0.join("example.spb");
    if let Err(error) = std::fs::write(&bytecode, &compiled.bytes) { return Ok(Execution::CompileOnly(error.to_string())); }
    let exe = match std::env::current_exe() { Ok(exe) => exe, Err(error) => return Ok(Execution::CompileOnly(error.to_string())) };
    let child = Command::new(exe)
        .arg("--doctest-exec").arg(&bytecode).current_dir(&dir.0)
        .env_clear().env("HOME", &dir.0).env("TMPDIR", &dir.0).env("TZ", "UTC").env("LANG", "C")
        .stdin(Stdio::null()).stdout(Stdio::piped()).stderr(Stdio::piped())
        .spawn();
    let mut running = RunningChild(match child { Ok(child) => child, Err(error) => return Ok(Execution::CompileOnly(error.to_string())) });
    let child = &mut running.0;
    let used = Arc::new(AtomicUsize::new(0));
    let exceeded = Arc::new(AtomicBool::new(false));
    let out = capture(child.stdout.take().unwrap(), used.clone(), exceeded.clone())?;
    let err = capture(child.stderr.take().unwrap(), used, exceeded.clone())?;
    let start = Instant::now();
    let mut reason = None;
    let status = loop {
        if exceeded.load(Ordering::Relaxed) { reason = Some("output limit exceeded"); }
        if start.elapsed() >= TIMEOUT { reason = Some("timeout (3 seconds)"); }
        if reason.is_some() {
            let _ = child.kill();
            break child.wait().map_err(|e| e.to_string())?;
        }
        match child.try_wait() {
            Ok(Some(status)) => break status,
            Ok(None) => std::thread::sleep(Duration::from_millis(10)),
            Err(error) => { let _ = child.kill(); let _ = child.wait(); return Err(error.to_string()); }
        }
    };
    let stdout = out.join().map_err(|_| "cannot capture doctest stdout")?.map_err(|e| e.to_string())?;
    let stderr = err.join().map_err(|_| "cannot capture doctest stderr")?.map_err(|e| e.to_string())?;
    if let Some(reason) = reason { return Err(reason.into()); }
    if exceeded.load(Ordering::Relaxed) { return Err("output limit exceeded".into()); }
    if !status.success() {
        if status.code() == Some(125)
            && let Ok(reason) = std::fs::read_to_string(bytecode.with_extension("unavailable")) {
            return Ok(Execution::CompileOnly(reason));
        }
        let mut trace = Vec::new();
        if let Ok(file) = std::fs::File::open(bytecode.with_extension("trace.json")) {
            let _ = file.take(OUTPUT as u64).read_to_end(&mut trace);
        }
        let locations = serde_json::from_slice::<Vec<[u32; 2]>>(&trace).map(|sites| compiled.locations(&sites)).unwrap_or_default();
        return Err(format!("isolated execution failed ({status}): {}{locations}", String::from_utf8_lossy(&stderr)));
    }
    Ok(Execution::Checked(stdout, stderr))
}

/// Private bytecode endpoint. All host capabilities are refused by Sparrow's
/// existing native policy; unknown natives fail closed too. Stdout/stderr and
/// computation remain available. Workers receive no spawning command.
pub(super) fn child(args: &[String]) -> Outcome {
    let [file] = args else { return Outcome::usage("--doctest-exec needs one bytecode file"); };
    if let Err(reason) = memory_watchdog().and_then(|()| {
        sparrow_core::budget::memory_probe().map(|_| ()).ok_or_else(|| "no process allocation probe".to_string())
    }) {
        let _ = std::fs::write(Path::new(file).with_extension("unavailable"), &reason);
        return Outcome::failure(reason, 125);
    }
    let input = match std::fs::File::open(file) { Ok(input) => input, Err(e) => return Outcome::failure(e.to_string(), EXIT_IO) };
    let mut bytes = Vec::new();
    if let Err(error) = input.take(okkama_sparrow::MAX_FILE_BYTES as u64 + 1).read_to_end(&mut bytes) {
        return Outcome::failure(error.to_string(), EXIT_IO);
    }
    let limits = sparrow_core::budget::Limits {
        memory: Some(MEMORY), memory_scope: sparrow_core::budget::MemoryScope::Process,
        output: Some(OUTPUT as u64), natives: Some(Vec::new()), ..Default::default()
    };
    let (outcome, uncaught) = core_described(sparrow_core::run_described(bytes, Vec::new(), false, Vec::new(), limits));
    if let Some(uncaught) = uncaught {
        let mut trace: Vec<_> = uncaught.trace.iter().take(1023).map(|site| [site.function, site.pc]).collect();
        if let Some(site) = uncaught.trace.last() { trace.push([site.function, site.pc]); }
        if let Ok(bytes) = serde_json::to_vec(&trace) {
            let _ = std::fs::write(Path::new(file).with_extension("trace.json"), bytes);
        }
    }
    outcome
}


/// Like the local cage's RSS bound, this also covers native libraries and JIT
/// allocations that a cooperative runtime heap budget cannot see. No OS or
/// working monitor means compile-only validation, never an unbounded run.
#[cfg(unix)]
fn memory_watchdog() -> Result<(), String> {
    use nix::sys::resource::{getrusage, UsageWho};
    getrusage(UsageWho::RUSAGE_SELF).map_err(|e| format!("process memory monitor: {e}"))?;
    std::thread::Builder::new().name("doctest-memory".into()).spawn(|| {
        let start = Instant::now();
        loop {
            if start.elapsed() >= TIMEOUT {
                let _ = writeln!(io::stderr(), "doctest timeout (3 seconds)");
                std::process::exit(1);
            }
            let used = getrusage(UsageWho::RUSAGE_SELF).map(|usage| usage.max_rss().max(0) as u64);
            let used = used.map(|rss| if cfg!(target_os = "macos") { rss } else { rss.saturating_mul(1024) });
            if used.is_err() || used.is_ok_and(|bytes| bytes > PROCESS_MEMORY) {
                let _ = writeln!(io::stderr(), "doctest process memory limit exceeded (256 MiB)");
                std::process::exit(1);
            }
            std::thread::sleep(Duration::from_millis(10));
        }
    }).map(|_| ()).map_err(|e| format!("process memory monitor: {e}"))
}

#[cfg(not(unix))]
fn memory_watchdog() -> Result<(), String> {
    Err("this platform has no process memory monitor".into())
}
