#!/usr/bin/env python3
"""Generate static HPACK rows from an explicitly supplied RFC 7541 text file."""
import argparse
import json
from pathlib import Path
import re

from okkama_fmt import formatted

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("rfc", type=Path)
parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "std/http/internal/hpack_static.ok")
args = parser.parse_args()
text = args.rfc.read_text()
start = text.index("Appendix A.  Static Table Definition", 10000)
section = text[start:]
section = section[:section.index("Appendix B.  Huffman Code")]
rows = re.findall(r"\|\s*(\d+)\s*\|\s*([^|]*?)\s*\|\s*([^|]*?)\s*\|", section)
if len(rows) != 61 or [int(row[0]) for row in rows] != list(range(1, 62)):
    raise ValueError("expected ordered 61-entry RFC static table")
docs = {"names": "Their names, in index order.", "values": "Their values, in index order."}
output = ["module http/internal/hpack_static v1.0.0;",
          "",
          "// The HPACK static table (RFC 7541 Appendix A), generated by",
          "// tools/generate-hpack-static.py.",
          "//",
          "// Internal to the http modules; programs do not import it.",
          "",
          "// Generated by tools/generate-hpack-static.py from RFC 7541 Appendix A.",
          "// https://www.rfc-editor.org/rfc/rfc7541.html#appendix-A",
          "object HpackStaticEntries {",
          "// The entries.",
          "HpackStaticEntries();"]
for column, name in [(1, "names"), (2, "values")]:
    output.append("// " + docs[name])
    output.append(name + "() is @string {[" + ",".join(json.dumps(row[column]) for row in rows) + "];}")
output.append("}")
output.append("""test "the static table is RFC 7541 Appendix A" {
let entries = HpackStaticEntries();
test.is(entries.names().size(), 61);
test.is(entries.values().size(), 61);
test.is(entries.names()[1], ":method");
test.is(entries.values()[1], "GET");
test.is(entries.names()[60], "www-authenticate");
}""")
# In the shape `okkama fmt` gives it (#1006).
args.output.write_text(formatted("\n".join(output) + "\n", args.output.name))
