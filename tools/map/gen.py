#!/usr/bin/env python3
"""Generated code maps (owner, 2026-11-20): docs/map/files.md and docs/map/rules.md.

    tools/map/gen.py            write the maps
    tools/map/gen.py --check    exit 1 when they differ from the code (CI)

files.md lists every non-test Rust source of okkama-rs/crates by layer and directory: lines of code and the
first line of its `//!` header. rules.md lists every rule tag the code cites (D25.3, B9, PR-B1, C-4, and the
rule codes the verifiers and the loader raise, such as SPB_SCHEDULE) with the layers and files that implement
or mention it, the tags that appear in more than one layer first: one rule, several implementations.

Both are generated: never edit them by hand. The hand-written maps are docs/map/README.md and its links.
"""
import argparse
import os
import re
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
CRATES = os.path.join(ROOT, "okkama-rs", "crates")
OUT = os.path.join(ROOT, "docs", "map")

# Path prefix (relative to crates/) → layer, first match wins.
LAYERS = [
    ("okkama-compiler/src/syntax", "front"),
    ("okkama-compiler/src/analysis", "front"),
    ("okkama-compiler/src/lowering", "lower"),
    ("okkama-compiler/src/ir", "ir"),
    ("okkama-compiler/src/codegen", "codegen"),
    ("okkama-compiler/src", "compiler"),
    ("okkama-sparrow/src", "spb"),
    ("sparrow-core/src/failures.rs", "ownership-runtime"),
    ("sparrow-core/src/tasks.rs", "ownership-runtime"),
    ("sparrow-core/src", "sparrow"),
    ("okkama-devtrace/src", "devtrace"),
    ("okkama-cli/src", "cli"),
]
# The layers that implement ownership: one rule should live in as few of them as possible (Tweed, #903).
OWNERSHIP = ["lower", "ir", "codegen", "ownership-runtime", "sparrow"]

TAG = re.compile(r"\b(D\d{1,2}(?:\.\d)?|PR-[A-Z]\d?|C-\d{1,2}|B\d{1,3})\b")
CODE = re.compile(r'"([A-Z][A-Z0-9]*_[A-Z0-9_]{2,})"')


def layer(relative):
    for prefix, name in LAYERS:
        if relative.startswith(prefix):
            return name
    return "other"


def sources():
    for directory, directories, names in os.walk(CRATES):
        directories[:] = sorted(d for d in directories if d not in ("target", "tests"))
        for name in sorted(names):
            if name.endswith(".rs") and not name.endswith("_tests.rs") and name != "tests.rs":
                path = os.path.join(directory, name)
                yield os.path.relpath(path, CRATES), path


def files_map():
    by_layer = defaultdict(list)
    for relative, path in sources():
        lines = open(path, encoding="utf-8").read().splitlines()
        code = sum(1 for line in lines if line.strip() and not line.strip().startswith("//"))
        header = next((line[3:].strip() for line in lines if line.startswith("//!") and line[3:].strip()), "")
        by_layer[layer(relative)].append((relative, code, header))
    out = ["# Source files by layer (generated by tools/map/gen.py; do not edit)", "",
           "Lines of code (no blank or comment lines) and the first line of each file's `//!` header. "
           "Tests (`*_tests.rs`, `tests/`) are left out.", ""]
    order = [name for _, name in LAYERS] + ["other"]
    seen = []
    for name in order:
        if name in seen or name not in by_layer:
            continue
        seen.append(name)
        entries = by_layer[name]
        out.append(f"## {name} — {len(entries)} files, {sum(code for _, code, _ in entries)} lines")
        out.append("")
        for relative, code, header in entries:
            out.append(f"- `{relative}` {code}" + (f" — {header[:110]}" if header else ""))
        out.append("")
    return "\n".join(out)


def rules_map():
    where = defaultdict(lambda: defaultdict(set))
    for relative, path in sources():
        name = layer(relative)
        for line in open(path, encoding="utf-8"):
            stripped = line.strip()
            tags = set()
            if stripped.startswith("//"):
                tags |= set(TAG.findall(stripped))
            tags |= set(CODE.findall(line))
            for tag in tags:
                where[tag][name].add(relative)
    multi = sorted((tag for tag in where if len(set(where[tag]) & set(OWNERSHIP)) > 1),
                   key=lambda tag: (-len(set(where[tag]) & set(OWNERSHIP)), tag))
    single = sorted(tag for tag in where if tag not in multi)
    out = ["# Rule tags and their implementations (generated by tools/map/gen.py; do not edit)", "",
           "A tag is a rule of the design documents cited in a comment (`D25.3`, `B9`, `PR-B1`, `C-4`) or a rule "
           "code raised in a string (`\"SPB_SCHEDULE\"`). **Before changing a rule, change it in every layer listed "
           "for it**, or know why not. Ownership layers: " + ", ".join(OWNERSHIP) + ".", "",
           f"## Tags in more than one ownership layer ({len(multi)})", "",
           "| tag | layers | files |", "|---|---|---|"]
    for tag in multi:
        layers = [name for name in OWNERSHIP + ["compiler", "spb", "cli", "other"] if name in where[tag]]
        files = "; ".join(f"{name}: " + ", ".join(f"`{f.split('/src/', 1)[-1]}`" for f in sorted(where[tag][name])[:4])
                          + (" …" if len(where[tag][name]) > 4 else "") for name in layers)
        out.append(f"| {tag} | {len(layers)} | {files} |")
    out += ["", f"## Tags in one layer ({len(single)})", ""]
    for tag in single:
        name, files = next(iter(where[tag].items()))
        out.append(f"- {tag} — {name}: " + ", ".join(f"`{f.split('/src/', 1)[-1]}`" for f in sorted(files)[:3])
                   + (" …" if len(files) > 3 else ""))
    out.append("")
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    maps = {"files.md": files_map(), "rules.md": rules_map()}
    stale = []
    for name, text in maps.items():
        path = os.path.join(OUT, name)
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if current != text:
            stale.append(name)
            if not args.check:
                os.makedirs(OUT, exist_ok=True)
                open(path, "w", encoding="utf-8").write(text)
    if args.check and stale:
        print(f"docs/map is stale: {', '.join(stale)}; run tools/map/gen.py", file=sys.stderr)
        return 1
    print("maps:", ", ".join(f"{name} {'updated' if name in stale else 'current'}" for name in maps))
    return 0


if __name__ == "__main__":
    sys.exit(main())
